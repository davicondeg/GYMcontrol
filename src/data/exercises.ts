export const catalogExercises = catalogExerciseData
  .filter((exercise) => exerciseImages[exercise.id])
  .map((exercise) => ({
    ...exercise,
    image: exerciseImages[exercise.id],
  }));

export function getCatalogExercise(id: string) {
  return catalogExercises.find((exercise) => exercise.id === id);
}

const normalizeExerciseText = (value: string) =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase('pt-BR')
    .trim();

export function resolveCatalogExercise(catalogId: string | null, name: string) {
  const exerciseById = catalogId ? getCatalogExercise(catalogId) : undefined;
  if (exerciseById) return exerciseById;

  const normalizedName = normalizeExerciseText(name);
  return catalogExercises.find((exercise) =>
    [exercise.name, ...(exercise.aliases ?? [])].some(
      (term) => normalizeExerciseText(term) === normalizedName,
    ),
  );
}

export function matchesExerciseSearch(exercise: CatalogExercise, query: string) {
  const normalizedQuery = normalizeExerciseText(query);
  return [exercise.name, ...(exercise.aliases ?? [])].some((term) =>
    normalizeExerciseText(term).includes(normalizedQuery),
  );
}
