begin;

create table public.daily_tracking (
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  water_ml integer not null default 0 check (water_ml >= 0),
  breakfast_done smallint not null default 0 check (breakfast_done in (0, 1)),
  morning_snack_done smallint not null default 0 check (morning_snack_done in (0, 1)),
  lunch_done smallint not null default 0 check (lunch_done in (0, 1)),
  afternoon_snack_done smallint not null default 0 check (afternoon_snack_done in (0, 1)),
  dinner_done smallint not null default 0 check (dinner_done in (0, 1)),
  supper_done smallint not null default 0 check (supper_done in (0, 1)),
  creatine_done smallint not null default 0 check (creatine_done in (0, 1)),
  whey_done smallint not null default 0 check (whey_done in (0, 1)),
  updated_at timestamptz not null default now(),
  primary key (user_id, date)
);

create table public.personal_exercises (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  catalog_id text,
  name text not null check (length(trim(name)) > 0),
  manual_image_uri text,
  personal_load text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, id),
  unique (user_id, catalog_id)
);

create table public.water_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  increment_1_ml integer not null default 500 check (increment_1_ml > 0),
  increment_2_ml integer not null default 800 check (increment_2_ml > 0),
  increment_3_ml integer not null default 1000 check (increment_3_ml > 0),
  updated_at timestamptz not null default now()
);

create table public.habit_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  type text not null check (type in ('meal', 'supplement')),
  label text not null check (length(trim(label)) > 0),
  sort_order integer not null,
  created_at timestamptz not null default now(),
  primary key (user_id, id)
);

create table public.daily_habit_completions (
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  habit_id text not null,
  done smallint not null default 0 check (done in (0, 1)),
  updated_at timestamptz not null default now(),
  primary key (user_id, date, habit_id),
  foreign key (user_id, habit_id)
    references public.habit_items(user_id, id) on delete cascade
);

create table public.workouts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, id)
);

create table public.workout_exercises (
  user_id uuid not null references auth.users(id) on delete cascade,
  workout_id bigint not null,
  personal_exercise_id bigint not null,
  position integer not null default 0,
  primary key (user_id, workout_id, personal_exercise_id),
  unique (user_id, personal_exercise_id),
  foreign key (user_id, workout_id)
    references public.workouts(user_id, id) on delete cascade,
  foreign key (user_id, personal_exercise_id)
    references public.personal_exercises(user_id, id) on delete cascade
);

create table public.workout_sessions (
  user_id uuid not null references auth.users(id) on delete cascade,
  key text not null,
  workout_id bigint not null,
  date date not null,
  completed_at timestamptz not null default now(),
  primary key (user_id, key),
  unique (user_id, workout_id, date),
  foreign key (user_id, workout_id)
    references public.workouts(user_id, id) on delete cascade
);

create index workout_sessions_user_date_idx
  on public.workout_sessions(user_id, date);

create table public.goal_versions (
  user_id uuid not null references auth.users(id) on delete cascade,
  effective_from date not null,
  workout_target_weekly integer not null check (workout_target_weekly between 0 and 14),
  water_goal_ml integer not null check (water_goal_ml between 0 and 10000),
  meal_target_daily integer not null check (meal_target_daily between 0 and 20),
  supplement_target_daily integer not null check (supplement_target_daily between 0 and 20),
  created_at timestamptz not null default now(),
  primary key (user_id, effective_from)
);

alter table public.daily_tracking enable row level security;
alter table public.personal_exercises enable row level security;
alter table public.water_settings enable row level security;
alter table public.habit_items enable row level security;
alter table public.daily_habit_completions enable row level security;
alter table public.workouts enable row level security;
alter table public.workout_exercises enable row level security;
alter table public.workout_sessions enable row level security;
alter table public.goal_versions enable row level security;

create policy "Users manage their daily tracking"
  on public.daily_tracking for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their personal exercises"
  on public.personal_exercises for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their water settings"
  on public.water_settings for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their habit items"
  on public.habit_items for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their habit completions"
  on public.daily_habit_completions for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their workouts"
  on public.workouts for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their workout exercises"
  on public.workout_exercises for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their workout sessions"
  on public.workout_sessions for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage their goal versions"
  on public.goal_versions for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

commit;
