begin;

create extension if not exists pgcrypto;

create table public.whatsapp_connections (
  user_id uuid primary key references auth.users(id) on delete cascade,
  wa_id text not null unique check (length(trim(wa_id)) > 0),
  display_phone text,
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.whatsapp_link_codes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  code_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table public.bot_messages (
  message_id text primary key,
  user_id uuid references auth.users(id) on delete set null,
  wa_id text not null,
  direction text not null check (direction in ('incoming', 'outgoing')),
  message_text text,
  intent text,
  status text not null default 'received' check (status in ('received', 'processed', 'failed', 'sent')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index bot_messages_user_created_idx on public.bot_messages(user_id, created_at desc);

create table public.bot_actions (
  id bigint generated by default as identity primary key,
  message_id text not null unique references public.bot_messages(message_id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  status text not null check (status in ('completed', 'rejected', 'failed')),
  input jsonb not null default '{}'::jsonb,
  result jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.whatsapp_connections enable row level security;
alter table public.whatsapp_link_codes enable row level security;
alter table public.bot_messages enable row level security;
alter table public.bot_actions enable row level security;

create policy "Users read and disconnect their WhatsApp"
  on public.whatsapp_connections for select using (auth.uid() = user_id);
create policy "Users disconnect their WhatsApp"
  on public.whatsapp_connections for delete using (auth.uid() = user_id);
create policy "Users read their WhatsApp link code"
  on public.whatsapp_link_codes for select using (auth.uid() = user_id);
create policy "Users read their bot messages"
  on public.bot_messages for select using (auth.uid() = user_id);
create policy "Users read their bot actions"
  on public.bot_actions for select using (auth.uid() = user_id);

create or replace function public.request_whatsapp_link_code()
returns table (code text, expires_at timestamptz)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  generated_code text;
  expiration timestamptz := now() + interval '10 minutes';
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  generated_code := lpad((floor(random() * 1000000))::integer::text, 6, '0');

  insert into public.whatsapp_link_codes (user_id, code_hash, expires_at, created_at)
  values (auth.uid(), encode(digest(generated_code, 'sha256'), 'hex'), expiration, now())
  on conflict (user_id) do update
    set code_hash = excluded.code_hash,
        expires_at = excluded.expires_at,
        created_at = excluded.created_at;

  return query select 'GYM-' || generated_code, expiration;
end;
$$;

revoke all on function public.request_whatsapp_link_code() from public;
grant execute on function public.request_whatsapp_link_code() to authenticated;

create or replace function public.bot_link_whatsapp(p_code text, p_wa_id text, p_display_phone text default null)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  linked_user_id uuid;
  normalized_code text := regexp_replace(upper(trim(p_code)), '^GYM-', '');
begin
  select user_id into linked_user_id
  from public.whatsapp_link_codes
  where code_hash = encode(digest(normalized_code, 'sha256'), 'hex')
    and expires_at > now()
  for update;

  if linked_user_id is null then
    return null;
  end if;

  delete from public.whatsapp_connections where wa_id = p_wa_id or user_id = linked_user_id;
  insert into public.whatsapp_connections (user_id, wa_id, display_phone)
  values (linked_user_id, p_wa_id, p_display_phone);
  delete from public.whatsapp_link_codes where user_id = linked_user_id;
  return linked_user_id;
end;
$$;

create or replace function public.bot_add_water(p_user_id uuid, p_date date, p_amount integer)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  total integer;
begin
  if p_amount <= 0 or p_amount > 10000 then
    raise exception 'Invalid water amount';
  end if;

  insert into public.daily_tracking (user_id, date, water_ml, updated_at)
  values (p_user_id, p_date, p_amount, now())
  on conflict (user_id, date) do update
    set water_ml = public.daily_tracking.water_ml + excluded.water_ml,
        updated_at = now()
  returning water_ml into total;

  return total;
end;
$$;

revoke all on function public.bot_link_whatsapp(text, text, text) from public, anon, authenticated;
revoke all on function public.bot_add_water(uuid, date, integer) from public, anon, authenticated;
grant execute on function public.bot_link_whatsapp(text, text, text) to service_role;
grant execute on function public.bot_add_water(uuid, date, integer) to service_role;

commit;
