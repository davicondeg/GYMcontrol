begin;

create table public.bot_outbox (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('evolution')),
  instance_name text not null,
  recipient text not null,
  message_text text not null check (length(trim(message_text)) between 1 and 4096),
  status text not null default 'queued' check (status in ('queued', 'sending', 'sent', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  available_at timestamptz not null default now(),
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  sent_at timestamptz
);

create index bot_outbox_delivery_idx
  on public.bot_outbox(status, available_at, created_at);

alter table public.bot_outbox enable row level security;
revoke all on table public.bot_outbox from public, anon, authenticated;
grant all on table public.bot_outbox to service_role;
grant usage, select on sequence public.bot_outbox_id_seq to service_role;

commit;
